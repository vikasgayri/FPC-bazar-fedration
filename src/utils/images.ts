import manifestJson from '@/data/image-manifest.json'

/* ───────────────────────── responsive sources ───────────────────────── */

export interface ImgMeta {
  w: number
  h: number
  v: number[]
  base: string
  lqip: string
}
const MANIFEST = manifestJson as Record<string, ImgMeta>
const UNSPLASH = /^https:\/\/images\.unsplash\.com\//
const WIDTHS = [480, 960, 1600]

export const imgMeta = (src: string): ImgMeta | undefined => MANIFEST[src.split('?')[0]]

const unsplashAt = (src: string, w: number) => {
  const u = new URL(src)
  u.searchParams.set('w', String(w))
  u.searchParams.set('q', '70')
  u.searchParams.set('auto', 'format')
  u.searchParams.set('fit', 'crop')
  return u.toString()
}

/**
 * Resolves an image path to optimised sources:
 *  • local photos → WebP variants generated by `npm run images` (see image-manifest.json)
 *  • Unsplash     → CDN-resized AVIF/WebP at 480 / 960 / 1600 px
 *  • anything else (admin uploads, data URLs) → as-is
 */
export function imgSources(src: string, preferred = 960): { src: string; srcSet?: string; meta?: ImgMeta } {
  const meta = imgMeta(src)
  if (meta) {
    const pick = meta.v.find((w) => w >= preferred) ?? meta.v[meta.v.length - 1]
    return { src: `${meta.base}-${pick}.webp`, srcSet: meta.v.map((w) => `${meta.base}-${w}.webp ${w}w`).join(', '), meta }
  }
  if (UNSPLASH.test(src)) return { src: unsplashAt(src, preferred), srcSet: WIDTHS.map((w) => `${unsplashAt(src, w)} ${w}w`).join(', ') }
  return { src }
}
